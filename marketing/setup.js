// ---- path binding --------------------------------------------------------------------
function getPath(obj, path) { return path.split(SEP).reduce((o, k) => (o == null ? undefined : o[k]), obj); }
function setPath(obj, path, val) {
  const keys = path.split(SEP); let o = obj;
  keys.slice(0, -1).forEach((k) => { if (o[k] == null) o[k] = {}; o = o[k]; });
  o[keys[keys.length - 1]] = val;
}
const field = (path, label, opts = {}) => {
  const v = getPath(P(), path) ?? '';
  const ph = opts.ph ? ` placeholder="${esc(opts.ph)}"` : '';
  let input;
  if (opts.options) input = `<select data-bind="${esc(path)}">${opts.options.map(([k, n]) => `<option value="${esc(k)}" ${k === v ? 'selected' : ''}>${esc(n)}</option>`).join('')}</select>`;
  else if (opts.rows) input = `<textarea data-bind="${esc(path)}" rows="${opts.rows}"${ph}>${esc(v)}</textarea>`;
  else input = `<input data-bind="${esc(path)}" value="${esc(v)}"${ph}${opts.type ? ` type="${opts.type}"` : ''}>`;
  return `<label><span class="label">${esc(label)}</span>${input}</label>`;
};
const secretField = (name, hint, opts = {}) => {
  const env = envName(name);
  const sensitive = /high|critical/i.test(opts.sensitivity || '') || /TOKEN|SECRET|PASSWORD|KEY|WEBHOOK/i.test(env);
  const agentMade = opts.agentMade;
  return `<div class="secret-row"><label><span class="label">${esc(name)}${agentMade ? ' · your agent can get this for you' : ''}</span>
    <input data-secret="${esc(env)}" type="${sensitive ? 'password' : 'text'}" autocomplete="off" spellcheck="false" value="${esc(secrets[env] || '')}" placeholder="${agentMade ? 'Leave blank: the agent gets it when you sign in through it' : 'Paste here'}"></label>
    ${hint ? `<span class="note">Where: ${linkify(esc(hint))}</span>` : ''}</div>`;
};
const envName = (name) => String(name).split(/\s/)[0];
const linkify = (html) => html.replace(/https?:\/\/[^\s<>"')\]]+/g, (u) => `<a href="${u}" target="_blank" rel="noopener">${u}</a>`);
const lines = (t) => String(t || '').split(/\n/).map((x) => x.trim()).filter(Boolean);
const urlsIn = (arr) => [...new Set((arr || []).join(' ').match(/https?:\/\/[^\s<>"')\],]+/g) || [])].map((u) => u.replace(/[.,]$/, ''));

