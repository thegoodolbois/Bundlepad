// ---- encrypted key vault (WebCrypto) -------------------------------------------------
async function vaultKey(pass, salt) {
  const base = await crypto.subtle.importKey('raw', new TextEncoder().encode(pass), 'PBKDF2', false, ['deriveKey']);
  return crypto.subtle.deriveKey({ name: 'PBKDF2', salt, iterations: 250000, hash: 'SHA-256' }, base, { name: 'AES-GCM', length: 256 }, false, ['encrypt', 'decrypt']);
}
const b64 = (buf) => btoa(String.fromCharCode(...new Uint8Array(buf)));
const unb64 = (s) => Uint8Array.from(atob(s), (c) => c.charCodeAt(0));
async function vaultSave(pass) {
  const salt = crypto.getRandomValues(new Uint8Array(16)); const iv = crypto.getRandomValues(new Uint8Array(12));
  const data = await crypto.subtle.encrypt({ name: 'AES-GCM', iv }, await vaultKey(pass, salt), new TextEncoder().encode(JSON.stringify(secrets)));
  return store.set('setup-vault:' + current, { salt: b64(salt), iv: b64(iv), data: b64(data) });
}
async function vaultOpen(pass) {
  const v = store.get('setup-vault:' + current, null);
  if (!v) throw new Error('no saved keys for this profile');
  const plain = await crypto.subtle.decrypt({ name: 'AES-GCM', iv: unb64(v.iv) }, await vaultKey(pass, unb64(v.salt)), unb64(v.data));
  return JSON.parse(new TextDecoder().decode(plain));
}

